#!/usr/bin/env python3
"""
Export docs/access-matrix.md: which scope opens each route and each MCP tool.

The document is built by asking the real matcher (auth/grants.py) about every
route the application serves and every tool it offers, once per scope, so it
shows what a scoped access key can reach rather than what a table says it
can. A change to what a key reaches -- a new route, a moved scope -- is
therefore a reviewed diff of that file.

Usage:
    python scripts/export_access_matrix.py           # rewrite the document
    python scripts/export_access_matrix.py --check   # exit 1 with a diff if stale
"""

from __future__ import annotations

import argparse
import asyncio
import difflib
import re
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import Any

DEFAULT_PATH = Path(__file__).resolve().parent.parent / "docs" / "access-matrix.md"

# The /api routes the root application serves itself, beside the mounted API
# app, and the MCP transport the gate lets a key reach.
ROOT_API_ROUTES = ("GET /api/events",)
MCP_TRANSPORT_ROUTES = ("GET /mcp/", "POST /mcp/", "DELETE /mcp/")

FULL_ONLY = "full access only"


def _route_entries(route: Any, prefix: str) -> Iterable[str]:
    """The "METHOD /path" entries of one route, HEAD left out."""
    methods = getattr(route, "methods", None) or {"GET"}
    for method in sorted(methods - {"HEAD"}):
        yield f"{method} {prefix}{route.path}"


def _walk(routes: Iterable[Any], prefix: str) -> Iterable[str]:
    """The entries of a FastAPI app's routes. An included router FastAPI keeps
    as a wrapper is followed, with the prefix it was included under."""
    from fastapi.routing import APIRoute
    from starlette.routing import Route

    for route in routes:
        if isinstance(route, APIRoute | Route):
            yield from _route_entries(route, prefix)
        elif hasattr(route, "original_router"):
            yield from _walk(route.original_router.routes, prefix + route.include_context.prefix)


def served_routes() -> list[str]:
    """Every "METHOD /path/{param}" a scoped key could ask for, sorted: the
    /api app's routes, the root application's own /api routes and the MCP
    transport."""
    from mail_verdict.server import build_api_app

    entries = set(_walk(build_api_app().routes, "/api"))
    entries.update(ROOT_API_ROUTES)
    entries.update(MCP_TRANSPORT_ROUTES)
    return sorted(entries, key=lambda e: (e.split(" ", 1)[1], e.split(" ", 1)[0]))


def concrete(route: str) -> tuple[str, str]:
    """The method and a request path that names `route`'s parameters."""
    method, template = route.split(" ", 1)
    return method, re.sub(r"\{[^}]+\}", "x", template)


def opening_scopes(route: str) -> list[str]:
    """The single scopes under which a key may call `route`, asked of the
    matcher; every scope for a route any scoped key may call, none for a
    route for full access only."""
    from mail_verdict.auth.grants import SCOPES, Grant, refusal_for_route

    method, path = concrete(route)
    return [
        scope for scope in SCOPES
        if refusal_for_route(Grant(frozenset({scope})), method, path) is None
    ]


def _cell(scopes: list[str]) -> str:
    from mail_verdict.auth.grants import SCOPES

    if not scopes:
        return FULL_ONLY
    if len(scopes) == len(SCOPES):
        return "every scope"
    return ", ".join(f"`{scope}`" for scope in scopes)


def served_tools() -> list[str]:
    """Every MCP tool the server offers, sorted."""
    from mail_verdict.api.mcp_tools import mcp

    return sorted(tool.name for tool in asyncio.run(mcp.list_tools()))


def opening_scopes_for_tool(tool: str) -> list[str]:
    """The single scopes under which a key may call `tool`."""
    from mail_verdict.auth.grants import SCOPES, Grant, refusal_for_tool

    return [
        scope for scope in SCOPES
        if refusal_for_tool(Grant(frozenset({scope})), tool) is None
    ]


def render_matrix() -> str:
    """The document's content, built from the code."""
    lines = [
        "# Access matrix",
        "",
        "What a scoped access key can reach. Generated by",
        "`scripts/export_access_matrix.py` from the route and tool tables in",
        "`src/mail_verdict/auth/grants.py` and the routes the application serves; the",
        "scopes are explained in the Access section of `docs/architecture.md`. A write",
        "scope also opens everything its read scope does. Anything a key's scopes do not",
        "open is refused with 403 `scope_required`.",
        "",
        "## Routes",
        "",
        "| Route | Opened by |",
        "|---|---|",
    ]
    lines += [f"| `{route}` | {_cell(opening_scopes(route))} |" for route in served_routes()]
    lines += ["", "## MCP tools", "", "| Tool | Opened by |", "|---|---|"]
    lines += [
        f"| `{tool}` | {_cell(opening_scopes_for_tool(tool))} |" for tool in served_tools()
    ]
    return "\n".join(lines) + "\n"


def stale_diff(path: Path) -> str:
    """A unified diff of the committed document against the code, or an empty
    string when it is current."""
    expected = render_matrix()
    actual = path.read_text(encoding="utf-8") if path.exists() else ""
    return "".join(difflib.unified_diff(
        actual.splitlines(keepends=True), expected.splitlines(keepends=True),
        fromfile=f"{path.name} (committed)", tofile=f"{path.name} (from code)",
    ))


def main(argv: list[str] | None = None) -> int:
    """
    Write or check the document.

    Args:
        argv: Command-line arguments, sys.argv[1:] when None

    Returns:
        Process exit code
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if the document is stale")
    parser.add_argument("--path", type=Path, default=DEFAULT_PATH, help="the document")
    args = parser.parse_args(argv)

    if args.check:
        diff = stale_diff(args.path)
        if diff:
            sys.stdout.write(diff)
            print(
                "\nThe access matrix is stale. Regenerate it with: "
                "python scripts/export_access_matrix.py",
                file=sys.stderr,
            )
            return 1
        return 0

    args.path.write_text(render_matrix(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
